// Adds the professional node's variables without touching any existing secret.
// Usage: node scripts/gen-env-pro.mjs [hub-url] [pro-node-url]
// Appends to .env.local (localhost URLs) and .env.vercel.production (deployed URLs), and writes node/.env.render-pro.
// Also writes .env.vercel.pro-only: the five lines to paste into Vercel. Nothing secret is printed.
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";

const [hub = "https://setu-live-five.vercel.app", url = "https://setu-college-pro.onrender.com"] = process.argv.slice(2);
const secret = () => randomBytes(32).toString("hex");
const s = { hub: secret(), viewer: secret(), mcp: secret(), node: secret(), admin: secret() };

const has = (file, key) => existsSync(file) && readFileSync(file, "utf8").split(/\r?\n/).some((l) => l.startsWith(`${key}=`));
if (has(".env.vercel.production", "NODE_PRO_HUB_TOKEN")) {
  console.log("Professional variables already exist in .env.vercel.production; nothing changed.");
  process.exit(0);
}

const block = (u) => `NODE_PRO_URL=${u}
NEXT_PUBLIC_NODE_PRO_URL=${u}
NODE_PRO_HUB_TOKEN=${s.hub}
NODE_PRO_VIEWER_SECRET=${s.viewer}
NODE_PRO_MCP_TOKEN=${s.mcp}
`;
appendFileSync(".env.vercel.production", `\n${block(url)}`);
writeFileSync(".env.vercel.pro-only", block(url));
appendFileSync(".env.local", `\n# Professional node (generated by scripts/gen-env-pro.mjs)\n${block("http://localhost:8003")}NODE_PRO_ADMIN_PASSWORD=${s.admin}\n`);
writeFileSync("node/.env.render-pro", `COLLEGE_ID=pro
COLLEGE_NAME=Setu Professionals
COLLEGE_CITY=Pan-India
NODE_SECRET=${s.node}
HUB_TOKEN=${s.hub}
VIEWER_SECRET=${s.viewer}
MCP_TOKEN=${s.mcp}
ADMIN_PASSWORD=${s.admin}
HUB_ORIGIN=${hub}
PUBLIC_URL=${url}
TRUST_PROXY=1
DB_PATH=./setu.db
`);
console.log("Wrote node/.env.render-pro and .env.vercel.pro-only; appended to .env.vercel.production and .env.local (all git-ignored).");
