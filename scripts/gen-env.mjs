// Generates the round-2 secrets once and writes git-ignored env files you can paste into Vercel and Render.
// Usage: node scripts/gen-env.mjs [hub-url] [ngit-node-url] [rce-node-url]
// Writes: .env.vercel.production, node/.env.render-ngit, node/.env.render-rce, and appends the local block to .env.local
import { randomBytes } from "node:crypto";
import { appendFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";

const [hub = "https://oddyssey-nu.vercel.app", ngit = "https://setu-node-ngit.onrender.com", rce = "https://setu-node-rce.onrender.com"] = process.argv.slice(2);
const secret = () => randomBytes(32).toString("hex");

const s = {
  session: secret(), hop: secret(), stage: secret(),
  ngit: { hub: secret(), viewer: secret(), mcp: secret(), node: secret(), admin: secret() },
  rce: { hub: secret(), viewer: secret(), mcp: secret(), node: secret(), admin: secret() },
};

const hubBlock = (urls) => `HUB_SESSION_SECRET=${s.session}
HOP_TOKEN_SECRET=${s.hop}
DEMO_STAGE_KEY=${s.stage}
NODE_NGIT_URL=${urls.ngit}
NODE_RCE_URL=${urls.rce}
NEXT_PUBLIC_NODE_NGIT_URL=${urls.ngit}
NEXT_PUBLIC_NODE_RCE_URL=${urls.rce}
NODE_NGIT_HUB_TOKEN=${s.ngit.hub}
NODE_RCE_HUB_TOKEN=${s.rce.hub}
NODE_NGIT_VIEWER_SECRET=${s.ngit.viewer}
NODE_RCE_VIEWER_SECRET=${s.rce.viewer}
NODE_NGIT_MCP_TOKEN=${s.ngit.mcp}
NODE_RCE_MCP_TOKEN=${s.rce.mcp}
`;

const nodeBlock = (id, name, city, url, n) => `COLLEGE_ID=${id}
COLLEGE_NAME=${name}
COLLEGE_CITY=${city}
NODE_SECRET=${n.node}
HUB_TOKEN=${n.hub}
VIEWER_SECRET=${n.viewer}
MCP_TOKEN=${n.mcp}
ADMIN_PASSWORD=${n.admin}
HUB_ORIGIN=${hub}
PUBLIC_URL=${url}
TRUST_PROXY=1
DB_PATH=./setu.db
`;

writeFileSync(".env.vercel.production", hubBlock({ ngit, rce }));
writeFileSync("node/.env.render-ngit", nodeBlock("ngit", "Northgate Institute of Technology", "Delhi", ngit, s.ngit));
writeFileSync("node/.env.render-rce", nodeBlock("rce", "Riverbend College of Engineering", "Noida", rce, s.rce));

// local development: hub on :3000, nodes on :8001 / :8002 with the same secrets
const local = hubBlock({ ngit: "http://localhost:8001", rce: "http://localhost:8002" });
const current = existsSync(".env.local") ? readFileSync(".env.local", "utf8") : "";
if (current.includes("HUB_SESSION_SECRET=")) console.log(".env.local already has round-2 secrets; left unchanged.");
else appendFileSync(".env.local", `\n# Round 2 (generated by scripts/gen-env.mjs)\n${local}`);
console.log("Wrote .env.vercel.production, node/.env.render-ngit, node/.env.render-rce (all git-ignored). Secrets are not printed.");
